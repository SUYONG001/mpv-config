-- ==============================================================================
-- quack.lua — 拖动进度条时自动降低音量的防刺耳脚本
-- ==============================================================================
-- 功能概述：
--   1. 监听 mpv 的 "seeking" 属性（拖动进度条时为 true，松手后为 false）
--   2. 一旦检测到拖动行为，立即把音量降低到原音量的 duckratio 倍
--   3. 拖动结束后，用 ducksecs 秒把音量平滑地恢复到原始音量
--   4. 效果：拖动进度条时不会因为音频频繁跳转而产生刺耳爆音
-- ==============================================================================
-- 原脚本来源：mpv 社区常用脚本（quack.lua）
-- 完成全量中文注释解析
-- ==============================================================================

-- 引入 mpv 的配置读取模块
local options = require 'mp.options'

-- ==============================================================================
-- 1. 用户配置区 (Options)
-- 这些默认值可通过 script-opts/quack.conf 文件覆盖修改
-- ==============================================================================
local o = {
    -- 拖动结束后，音量从"降低状态"恢复到"原始音量"所用的时间（秒）
    -- 数值越大，恢复越平滑；数值越小，恢复越快
    -- 默认 2 秒（舒缓恢复）
    ducksecs = 2,

    -- 拖动时把音量降到原音量的比例（0 ~ 1）
    --   0.0 = 完全静音（推荐用于消除刺耳声音）
    --   0.5 = 降到原音量的一半
    --   1.0 = 不降低音量（等于禁用此脚本）
    -- 默认 0.5
    duckratio = 0.5
}

-- 读取外部配置文件（quack.conf），覆盖上方默认值
options.read_options(o)

-- ==============================================================================
-- 2. 内部状态变量
-- ==============================================================================
local duck_progress = 0   -- 当前"恢复进度"计数（每 0.1 秒 +1，达到阈值后停止恢复）
local duck_timer = nil    -- 周期定时器（每 0.1 秒调用一次 update_quack）
local orig_vol = nil      -- 记录拖动前的原始音量，恢复时以此为目标

-- ==============================================================================
-- 3. 核心函数：逐帧平滑恢复音量 (update_quack)
-- 每次定时器触发（0.1 秒）时被调用一次，逐步把音量从"降低状态"拉回"原始音量"
-- ==============================================================================
function update_quack()
    -- 恢复进度 +1（每 0.1 秒 +1）
    duck_progress = duck_progress + 1

    -- 如果恢复进度已经达到上限（ducksecs 秒），停止定时器
    -- 注：ducksecs * 10 表示总帧数（因为每 0.1 秒一帧）
    if duck_progress >= o.ducksecs * 10 then
        duck_timer:kill()
    end

    -- 计算当前应该设置的音量：
    --   恢复初期：duck_progress 小，音量 ≈ orig_vol * duckratio（完全降低）
    --   恢复后期：duck_progress 大，音量 ≈ orig_vol（完全恢复）
    -- 使用 math.min 确保音量不会超过原始音量
    mp.set_property_number("volume", math.min(
        orig_vol,
        orig_vol * o.duckratio
        + orig_vol * (1 - o.duckratio) * (duck_progress / (o.ducksecs * 10))
    ))
end

-- ==============================================================================
-- 4. 触发函数：监听 seeking 属性变化 (engage_ducking)
-- mpv 在拖动进度条时会把 "seeking" 属性设为 true，松手后设为 false
-- 每次该属性变化时，都会重新启动一次"降低→恢复"的流程
-- ==============================================================================
function engage_ducking(name, val)
    -- 获取当前播放进度（秒）
    pos = mp.get_property_number("time-pos")

    -- 如果 seeking 属性无效或为 false（表示没有在拖动），直接返回
    if val == nil or val == false then
        return
    end

    -- 如果当前播放位置为 0（文件刚开始），跳过音量调节
    -- 避免在文件还没开始播放时误触
    if pos == 0 then
        return
    end

    -- 重置恢复进度（让音量重新从"降低状态"开始）
    duck_progress = 0

    -- 定时器还没创建：首次触发时创建
    if duck_timer == nil then
        -- 创建一个每 0.1 秒执行一次 update_quack 的周期定时器
        duck_timer = mp.add_periodic_timer(0.1, update_quack)

        -- 记录当前音量作为"原始音量"（恢复目标）
        orig_vol = mp.get_property_number("volume")

        -- 立即执行一次，确保拖动一开始音量就被降低
        update_quack()
    else
        -- 定时器已存在但已停止：重新启动
        if duck_timer:is_enabled() == false then
            orig_vol = mp.get_property_number("volume")
            duck_timer:resume()
            update_quack()
        end
    end
end

-- ==============================================================================
-- 5. 注册属性监听器
-- 监听 mpv 的 "seeking" 属性（布尔值），一旦变化就调用 engage_ducking
-- ==============================================================================
mp.observe_property("seeking", "bool", engage_ducking)